import { test, expect } from './server';

test('a queued book starts its own audio without marking another book started', async ({ page, server }) => {
  await page.goto(server.url);
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill('owner');
  await page.getByLabel('Password', { exact: true }).fill('fixture-password-123');
  await page.getByLabel('Confirm password', { exact: true }).fill('fixture-password-123');
  const setup = page.waitForResponse(response => response.url().endsWith('/api/auth/setup') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create owner', exact: true }).click();
  server.token = (await (await setup).json()).token;
  await expect(page.locator('.book-row')).toHaveCount(2);
  const books = await server.books();
  const first = books.find(book => book.title === 'First Book')!;
  const second = books.find(book => book.title === 'Second Book')!;
  await expect(page.getByRole('heading', { name: 'Up Next', exact: true })).toHaveCount(0);
  await page.locator('.book-row').filter({ hasText: 'Second Book' }).click();
  await page.getByRole('button', { name: 'Add Second Book to Up Next', exact: true }).click();
  await expect(page.locator('.book-quick-queue')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.queue-row')).toHaveCount(1);
  await page.locator('.book-quick-queue').click();
  await expect(page.locator('.queue-row')).toHaveCount(0);
  await page.locator('.book-quick-queue').click();
  await expect(page.locator('.queue-row')).toHaveCount(1);
  await expect(page.getByRole('button', { name: /^Continue reading/ })).toHaveCount(0);
  expect(await server.progress(second.id)).toBeNull();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open library', exact: true }).click();
  await page.getByRole('button', { name: 'Open Second Book', exact: true }).click();
  await expect(page.locator('.library-pane')).not.toHaveClass(/\bopen\b/);
  await expect(page.getByRole('heading', { name: 'Second Book', exact: true })).toBeVisible();
  expect(await server.progress(second.id)).toBeNull();
  await page.getByRole('button', { name: 'Open library', exact: true }).click();
  await page.getByRole('button', { name: 'Start Second Book', exact: true }).click();
  await expect.poll(() => page.locator('audio').evaluate((audio: HTMLAudioElement) => audio.currentTime)).toBeGreaterThan(2);
  await expect(page.getByRole('button', { name: 'Continue reading Second Book', exact: true })).toHaveCount(1);
  await expect(page.locator('.queue-row')).toHaveCount(0);
  await page.getByRole('button', { name: 'Open library', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause Second Book', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pause Second Book', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Play Second Book', exact: true })).toBeVisible();
  await expect.poll(async () => (await server.progress(second.id))?.bookPositionSeconds ?? 0).toBeGreaterThan(1);
  expect(await server.progress(first.id)).toBeNull();

  // In progress, it stays in Up Next by itself and no longer offers to be planned.
  await expect(page.getByRole('region', { name: 'Listening and queue', exact: true }).getByRole('listitem')).toHaveCount(1);
  await expect(page.getByRole('heading', { name: 'Now listening', exact: true })).toBeVisible();
  await page.locator('.book-row').filter({ hasText: 'Second Book' }).click();
  await expect(page.locator('.book-quick-queue')).toHaveCount(0);
});

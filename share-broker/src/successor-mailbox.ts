// Isolated prototype. No Worker route invokes this module.
import { authenticateOwner, type Claim, type TransactionalStorage } from "./claims.js";

type Member = { room: string; nonce: string; expiresAt: number; digest: number[]; state: "empty" | "ready" | "consumed"; envelope?: Envelope };
export type Envelope = { nonce: string; ciphertext: string };
const identifier = /^[A-Za-z0-9_-]{16,128}$/;
// Canonical unpadded base64url of 32 bytes, including zero padding bits.
const secretPattern = /^[A-Za-z0-9_-]{42}[AEIMQUYcgkosw048]$/;
const envelopeNonce = /^[A-Za-z0-9_-]{16}$/;
const ciphertext = /^[A-Za-z0-9_-]{22,10924}$/;
const key = "secure-successor:recipient";

function scoped(room: string, claim: Claim): boolean {
  return typeof room === "string" && identifier.test(room) && !!claim && claim.room === room && claim.role === "recipient" && typeof claim.nonce === "string" && identifier.test(claim.nonce) && claim.previousNonce === undefined && Number.isSafeInteger(claim.expiresAt);
}

function matches(member: Member | undefined, room: string, claim: Claim, now: number): member is Member {
  return !!member && member.room === room && member.nonce === claim.nonce && member.expiresAt === claim.expiresAt && member.expiresAt > now;
}

/** Caller verifies the initial owner-signed claim; secret must be generated by the recipient with a CSPRNG. */
export async function claimMailbox(storage: TransactionalStorage, room: string, claim: Claim, secret: string, clock: () => number): Promise<boolean> {
  if (!scoped(room, claim) || typeof secret !== "string" || !secretPattern.test(secret)) return false;
  const digest = Array.from(new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(secret))));
  return storage.transaction(async txn => {
    const now = clock();
    if (claim.expiresAt <= now || claim.expiresAt > now + 900 || await txn.get("revoked") || await txn.get(key)) return false;
    await txn.put(key, { room, nonce: claim.nonce, expiresAt: claim.expiresAt, digest, state: "empty" } satisfies Member);
    return true;
  });
}

/** Caller authenticates the owner and verifies that the encrypted successor is appropriately scoped. */
export async function publishSuccessor(storage: TransactionalStorage, room: string, claim: Claim, envelope: Envelope, clock: () => number): Promise<boolean> {
  if (!scoped(room, claim) || !envelope || typeof envelope.nonce !== "string" || !envelopeNonce.test(envelope.nonce) || typeof envelope.ciphertext !== "string" || !ciphertext.test(envelope.ciphertext)) return false;
  return storage.transaction(async txn => {
    const member = await txn.get<Member>(key);
    if (await txn.get("revoked") || !matches(member, room, claim, clock()) || member.state !== "empty") return false;
    await txn.put(key, { ...member, state: "ready", envelope: { nonce: envelope.nonce, ciphertext: envelope.ciphertext } });
    return true;
  });
}

/** A successful read consumes the envelope atomically; a lost response cannot be retried. */
export async function consumeSuccessor(storage: TransactionalStorage, room: string, claim: Claim, secret: string, clock: () => number): Promise<Envelope | null> {
  if (!scoped(room, claim) || typeof secret !== "string" || !secretPattern.test(secret)) return null;
  return storage.transaction(async txn => {
    const member = await txn.get<Member>(key);
    if (await txn.get("revoked") || !matches(member, room, claim, clock()) || member.state !== "ready" || !member.envelope || !await authenticateOwner(secret, Uint8Array.from(member.digest))) return null;
    // Recheck the clock after asynchronous cryptography and before committing.
    if (member.expiresAt <= clock()) return null;
    const result = member.envelope;
    await txn.put(key, { room: member.room, nonce: member.nonce, expiresAt: member.expiresAt, digest: member.digest, state: "consumed" } satisfies Member);
    return result;
  });
}
